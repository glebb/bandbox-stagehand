"""Turns measure.py's readings into Stagehand's tables: Sources/Shared/SongTones/BandBoxCalibration.swift.

    analyse.py GAINS TRANSFER > ../Stagehand/Sources/Shared/SongTones/BandBoxCalibration.swift

GAINS is a run with steps, amps, volume, cabs and eq (data/usb-1.jsonl), TRANSFER one with transfer
(data/usb-2.jsonl). Levels are dB at the speaker's USB feed with the channel's volume at 8, the amp's
Volume at 50, its own tone knobs and the UK 1960 cab; inputs are dB around the test signal (the Precision
Drive at full on a guitar's idle noise)."""
import json, sys, collections
import numpy as np
from measure import AMPS, CABS, REF_CAB

gains = [json.loads(l) for l in open(sys.argv[1])]
transfer = [json.loads(l) for l in open(sys.argv[2])]

# The channel volume's steps, loud and quiet settings joined where they overlap, as dB to add to a reading to bring it to volume 8.
loud = {r["vol"]: r["level"] for r in gains if r["what"] == "channel volume" and r["setting"] == "loud"}
quiet = {r["vol"]: r["level"] for r in gains if r["what"] == "channel volume" and r["setting"] == "quiet"}
shift = np.mean([loud[v] - quiet[v] for v in loud if v in quiet])
law = dict(loud); law.update({v: l + shift for v, l in quiet.items() if v not in loud})
to8 = {v: law[8] - l for v, l in law.items()}

def at8(r): return r["level"] + to8[r["vol"]]

# Each amp's level over Drive with the plain test signal (input 0).
by_drive = collections.defaultdict(dict)
for r in gains:
    if r["what"] == "amp" and r["source"] == 100: by_drive[r["amp"]][r["drive"]] = at8(r)

# The amp's Volume, around 50: the same for every amp measured.
vol = collections.defaultdict(dict)
for r in gains:
    if r["what"] == "amp volume": vol[r["amp"]][r["volume"]] = at8(r)
volume = {v: float(np.mean([vol[a][v] - vol[a][50] for a in vol])) for v in sorted(next(iter(vol.values())))}
spread = max(abs(vol[a][v] - vol[a][50] - volume[v]) for a in vol for v in volume)

# Cabs: all the bands together, around the reference cab.
def total(r): return 10 * np.log10(sum(10 ** (b / 10) for b in r["bands"])) + to8[r["vol"]]
cab = {r["cab"]: total(r) for r in gains if r["what"] == "cab"}
cabs = {name: cab[name] - cab[CABS[REF_CAB]] for name in cab}

# Tone knobs: dB per knob step around the middle, the mean of the amps measured.
eq = collections.defaultdict(list)
for r in gains:
    if r["what"] == "amp eq": eq[(r["amp"], r["knob"])].append((r["value"], at8(r)))
slope = {k: float(np.mean([np.polyfit(*zip(*eq[(a, kk)]), 1)[0] for (a, kk) in eq if kk == k])) for k in ("bass", "mid", "treble")}

# Transfer: output over input per amp and Drive. A run whose output level moved on the way (the computer's or the
# speaker's volume turned: the feed follows them) is put back on GAINS' level where both have the amp at input 0.
src = {r["step"]: at8(r) for r in transfer if r["what"] == "source"}
inputs = [src[i] - src[4] for i in sorted(src)]
curves = collections.defaultdict(dict)
for r in transfer:
    if r["what"] == "transfer": curves[(r["amp"], r["drive"])][r["step"]] = at8(r)
table = {}
for a in AMPS[:8]:
    rows = []
    for d in (0, 25, 50, 75, 100):
        c = [curves[(a, d)][i] for i in range(len(inputs))]
        rows.append(c)
    # The offset to GAINS, from the Drives both runs have and where the amp still follows its input.
    offs = []
    for row, d in zip(rows, (0, 25, 50, 75, 100)):
        if d in by_drive[a] and (row[5] - row[3]) / (inputs[5] - inputs[3]) > 0.8: offs.append(by_drive[a][d] - row[4])
    table[a] = (rows, offs)
# One offset for the amps measured after the level moved; none for those before.
moved = [np.median(o) for a, (rows, o) in table.items() if o and abs(np.median(o)) > 3]
late = float(np.mean(moved)) if moved else 0.0
out, after = {}, False
for a, (rows, offs) in table.items():
    after = after or bool(offs and abs(np.median(offs)) > 3)   # every amp from the first that shows the move
    fixed = []
    for row in rows:
        # A row that jumps the wrong way partway: the level moved inside it; the points after the jump get the offset.
        row = list(row)
        if after: row = [x + late for x in row]
        else:
            for i in range(1, len(row)):
                if row[i] < row[i - 1] - 2: row[i:] = [x + late for x in row[i:]]; break
        fixed.append(row)
    out[a] = fixed

def nums(xs, f="%.1f"): return "[" + ", ".join(f % x for x in xs) + "]"

print("""// Generated by tone-bench/analyse.py from measurements of a BandBox Trio (tone-bench/data): don't edit, measure again.
// How the amps, cabs and knobs change a tone's level and how hard an amp is driven, for GearMatch.

enum BandBoxCalibration {
    /// A guitar being played, in dB around the bench's test signal: where a tone is read off the curves below.
    /// Not measured yet: between the hottest test signal (+18) and where the amps' own defaults sound as JBL names them.
    static let guitar = 8.0

    /// The input levels the amps were measured at, dB around the test signal.
    static let inputs: [Double] = %s
    /// The Drive settings they were measured at.
    static let drives: [Double] = [0, 25, 50, 75, 100]
    /// Each guitar amp's output in dB (Volume 50, its own tone knobs, the UK 1960 cab) by Drive, then by input.
    static let amps: [UInt16: [[Double]]] = [""" % nums(inputs))
for i, a in enumerate(AMPS[:8]):
    print("        0x%04X: [   // %s" % (i << 8 | 6, a))
    for row in out[a]: print("            %s," % nums(row))
    print("        ],")
print("""    ]

    /// The amp's Volume knob in dB around 50, the same on every amp (within %.1f dB on the three measured).
    static let volume: [(knob: Double, dB: Double)] = [%s]

    /// Each cab's level in dB around the UK 1960's, with a driven amp; `cabOff` with the cab switched off.
    static let cabs: [UInt16: Double] = [%s]
    static let cabOff = %.1f

    /// The tone knobs: dB a step, around the model's own setting (the mean of three amps; the bass knob does next to nothing).
    static let mid = %.3f, treble = %.3f

    /// The Precision Drive's gain in dB by its Drive, with Bright and Level at 100, and what Level and Bright take off.
    static let pedalDrive: [(knob: Double, dB: Double)] = [(0, 3.6), (20, 9.3), (40, 14.2), (60, 23.2), (70, 28.8), (80, 34.2), (90, 39.3), (100, 44.0)]
    static let pedalLevel: [(knob: Double, dB: Double)] = [%s]
    static let pedalBright = 0.06     // dB a step below 100
    /// The compressor's Output: dB a step, from 0 (no gain).
    static let compressorOutput = 0.18
}""" % (spread, ", ".join("(%d, %.1f)" % (v, d) for v, d in volume.items()),
        ", ".join("0x%04X: %.1f" % (i << 8 | 8, cabs[n]) for i, n in enumerate(CABS)), cabs["off"],
        slope["mid"], slope["treble"],
        ", ".join("(%d, %.1f)" % (r["knob"], at8(r) - [at8(x) for x in gains if x["what"] == "source level" and x["knob"] == 100][0])
                  for r in sorted((x for x in gains if x["what"] == "source level"), key=lambda x: x["knob"]))))
print("// late offset %.2f dB, tone knob slopes %s" % (late, slope), file=sys.stderr)
